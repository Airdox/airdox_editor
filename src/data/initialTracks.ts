// Helper to generate realistic waveform peak bars
function generateWaveform(seed: number, bars = 96): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < bars; i++) {
    // structured curve with breakdowns and drops
    const pos = i / bars;
    let base = 0.35 + 0.3 * Math.sin(pos * Math.PI * 3 + seed);
    // Add drop intensity
    if ((pos > 0.25 && pos < 0.45) || (pos > 0.65 && pos < 0.85)) {
      base = Math.min(0.98, base + 0.35 + 0.15 * Math.sin(i * 0.9));
    }
    // Breakdown dips
    if ((pos >= 0.45 && pos <= 0.55) || pos < 0.08 || pos > 0.92) {
      base = Math.max(0.12, base * 0.4);
    }
    const noise = ((Math.sin(i * 12.3 + seed) + 1) / 2) * 0.2;
    peaks.push(Math.round(Math.min(1.0, Math.max(0.08, base + noise)) * 100) / 100);
  }
  return peaks;
}

