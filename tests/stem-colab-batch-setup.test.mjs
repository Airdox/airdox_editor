import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const python = process.env.AIRODOX_STEM_PYTHON || (process.platform === 'win32' ? 'python' : 'python3');
const result = spawnSync(python, ['-m', 'unittest', 'discover', '-s', 'tests', '-p', 'test_colab_batch_setup.py', '-v'], { cwd: root, encoding: 'utf8', windowsHide: true });
assert.ifError(result.error);
assert.equal(result.status, 0, result.stdout + result.stderr);
const notebook = JSON.parse(readFileSync(new URL('../colab/airdox-top200-batch.ipynb', import.meta.url), 'utf8'));
const code = notebook.cells.filter(c => c.cell_type === 'code').map(c => c.source.join('')).join('\n');
assert.match(code, /retry_failed=FEHLGESCHLAGENE_WIEDERHOLEN/);
assert.match(code, /FEHLGESCHLAGENE_WIEDERHOLEN = False/);
assert.match(code, /prepare_model/);
assert.doesNotMatch(code, /git.*clone|Vorhandenen Quellcode wiederverwendet/);
const compile = spawnSync(python, ['-c', 'import ast,json,sys; n=json.load(open(sys.argv[1],encoding="utf-8")); [ast.parse("".join(c["source"])) for c in n["cells"] if c["cell_type"]=="code"]', 'colab/airdox-top200-batch.ipynb'], { cwd: root, encoding: 'utf8', windowsHide: true });
assert.equal(compile.status, 0, compile.stderr);
console.log(result.stderr.trim());
console.log('Batch notebook recovery contract and Python cells passed');
