import assert from 'node:assert/strict';
import { planQueueMigration, BATCH_QUEUE_WAIT_MS } from '../src/stems/remote/queueMigration.mjs';
const record = { jobId: 'same-job', workingCopySha256: 'a'.repeat(64), modelId: 'model', profile: 'HIGH', status: 'FAILED', error: { code: 'REMOTE_TIMEOUT' }, finishedAt: 10 };
const manifest = { jobId: 'same-job', input: { sha256: 'a'.repeat(64) }, engine: { modelId: 'model', profile: 'HIGH' }, status: 'FAILED', error: { code: 'REMOTE_TIMEOUT' }, output: { stems: [] } };
const repaired = planQueueMigration(record, manifest);
assert.equal(repaired.action, 'repair-timeout');
assert.equal(repaired.record.queueWaitTimeoutMs, BATCH_QUEUE_WAIT_MS);
assert.equal(repaired.record.jobId, record.jobId);
assert.equal(repaired.record.workingCopySha256, record.workingCopySha256);
assert.equal(repaired.record.error, undefined);
assert.equal(record.status, 'FAILED');
assert.equal(planQueueMigration(record, { ...manifest, status: 'COMPLETED' }).action, 'import');
assert.equal(planQueueMigration(record, manifest, { claim: { id: 'old-worker' } }).action, 'skip');
assert.equal(planQueueMigration({ ...record, worker: {} }, manifest).action, 'skip');
assert.equal(planQueueMigration(record, { ...manifest, error: { code: 'REMOTE_WORKER_FAILED' } }).action, 'skip');
assert.equal(planQueueMigration(record, manifest, { cancelled: true }).action, 'skip');
assert.equal(planQueueMigration(record, { ...manifest, input: { sha256: 'different' } }).action, 'skip');
assert.equal(planQueueMigration({ ...record, status: 'RUNNING', error: undefined }, { ...manifest, status: 'RUNNING', error: undefined }).action, 'extend-wait');
assert.equal(planQueueMigration({ ...record, status: 'RUNNING', error: undefined, queueWaitTimeoutMs: BATCH_QUEUE_WAIT_MS }, { ...manifest, status: 'RUNNING', error: undefined }).reason, 'already-migrated');
console.log('Queue migration: same identity, completed priority, no claimed/error/cancel resets');
